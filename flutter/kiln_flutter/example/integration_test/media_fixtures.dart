/// A two-second 440 Hz tone as a 16-bit mono WAV file at 16 kHz.
Uint8List toneWav({double seconds = 2, int rate = 16000, double hz = 440}) {
  final n = (seconds * rate).round();
  final data = ByteData(44 + n * 2);
  void tag(int at, String s) {
    for (var i = 0; i < 4; i++) {
      data.setUint8(at + i, s.codeUnitAt(i));
    }
  }

  tag(0, 'RIFF');
  data.setUint32(4, 36 + n * 2, Endian.little);
  tag(8, 'WAVE');
  tag(12, 'fmt ');
  data.setUint32(16, 16, Endian.little); // size of the fmt block
  data.setUint16(20, 1, Endian.little); // PCM
  data.setUint16(22, 1, Endian.little); // mono
  data.setUint32(24, rate, Endian.little);
  data.setUint32(28, rate * 2, Endian.little); // bytes per second
  data.setUint16(32, 2, Endian.little); // bytes per sample
  data.setUint16(34, 16, Endian.little); // bits per sample
  tag(36, 'data');
  data.setUint32(40, n * 2, Endian.little);
  for (var i = 0; i < n; i++) {
    data.setInt16(44 + i * 2, (math.sin(2 * math.pi * hz * i / rate) * 12000).round(), Endian.little);
  }
  return data.buffer.asUint8List();
}
